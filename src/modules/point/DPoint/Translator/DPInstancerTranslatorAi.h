#pragma once

#include "platform/Platform.h"

#include "translators/DagTranslator.h"
#include "translators/NodeTranslator.h"
#include "translators/shape/ShapeTranslator.h"
#include "DTransformOp.h"
#include "integrations/arnold/DArnoldResources.h"

#include <string>
#include <vector>







class DPInstancerTranslatorAi : public CShapeTranslator
{
public:
	AtNode* CreateArnoldNodes();
	void Export(AtNode*);
	void Update(AtNode*);
	void ExportMotion(AtNode* atNode);
	static void* creator();
		
	void NodeChanged(MObject& node, MPlug& plug);
	virtual bool RequiresMotionData();
	
private:
	// Remove the Arnold nodes generated by the previous update.
	bool deleteInstancedNodes(bool deleteReferenceNodes);
    // Successful inactive/empty states keep the imported ASS reference cache.
    bool retireGeneratedNodes();

	// Load and cache the reference nodes from the configured ASS file.
	bool refreshReferenceFile();

	MStatus evalAnimMatrixParms(DTransformParams& parms);
	void instanceAssignDPAttribute(
		const DPData* dPoints,
		const MStringArray& attributeNameArray,
		AtNode* inst,
		size_t instIndex);
	AtNode* generateAiMeshFromMPlug(
		MDataHandle inMeshHnd,
		unsigned int numMotionStep);

    bool shouldRefreshAss = true;
    dommy::arnold::NodeBatch pendingNodes_;
    std::string referenceNodePrefix;
    // Borrowed universe pointers introduced by this translator's ASS import.
    // Names select instanced shapes but never establish deletion ownership.
    std::vector<AtNode*> ownedReferenceNodes;
    std::vector<AtNode*> refNodeList;
	
};
